import React from "react";
import { SortableItem } from "./SortableItem";
import type { DashboardNode } from "../api";

function moveItem<T>(items: T[], from: number, to: number): T[] {
  const copy = [...items];
  const [moved] = copy.splice(from, 1);

  if (moved !== undefined) {
    copy.splice(to, 0, moved);
  }

  return copy;
}

type Props = {
  layout: "stack" | "grid";
  columns?: number;
  initialNodes: DashboardNode[];
  defaultNodes: DashboardNode[];
  editable: boolean;
  renderNode: (
    node: DashboardNode,
    onNodeChange: (nextNode: DashboardNode) => void
  ) => React.ReactNode;
  onLayoutChange: (nodes: DashboardNode[]) => void;
};

/**
 * Owns the current editable dashboard layout.
 * It deliberately does not use localStorage: the backend is the source of truth.
 */
export function SortableContainer({
  layout,
  columns,
  initialNodes,
  defaultNodes,
  editable,
  renderNode,
  onLayoutChange,
}: Props) {
  const [nodes, setNodes] = React.useState<DashboardNode[]>(initialNodes);
  const dragFrom = React.useRef<number | null>(null);
  const [dragOver, setDragOver] = React.useState<number | null>(null);

  const updateNodes = React.useCallback(
    (nextNodes: DashboardNode[]) => {
      setNodes(nextNodes);
      onLayoutChange(nextNodes);
    },
    [onLayoutChange]
  );

  // Populate dashboardLayout even before the first edit. Without this,
  // saving a brand-new dashboard without moving a card would save [] instead
  // of its generated sections.
  React.useEffect(() => {
    onLayoutChange(nodes);
    // The component is remounted with key={dashboardKey} for another dashboard.
    // We intentionally publish only on mount; edits use updateNodes above.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handleDragStart = (index: number) => {
    dragFrom.current = index;
  };

  const handleDragOver = (index: number) => {
    if (dragFrom.current === null || dragFrom.current === index) return;
    setDragOver(index);
  };

  const handleDrop = () => {
    const from = dragFrom.current;
    const to = dragOver;

    if (from !== null && to !== null && from !== to) {
      updateNodes(moveItem(nodes, from, to));
    }

    dragFrom.current = null;
    setDragOver(null);
  };

  const handleRemove = (index: number) => {
    updateNodes(nodes.filter((_, currentIndex) => currentIndex !== index));
  };

  const handleReset = () => {
    updateNodes(defaultNodes);
  };

  const cols = Number(columns) || 2;
  const containerStyle: React.CSSProperties =
    layout === "grid"
      ? {
          display: "grid",
          gridTemplateColumns: `repeat(${cols}, minmax(0, 1fr))`,
          gap: 16,
        }
      : { display: "flex", flexDirection: "column", gap: 16 };

  return (
    <div>
      {editable && (
        <div style={{ display: "flex", justifyContent: "flex-end", marginBottom: 8 }}>
          <button
            type="button"
            onClick={handleReset}
            style={{
              background: "transparent",
              border: "1px dashed #cbd5e1",
              borderRadius: 8,
              padding: "4px 10px",
              fontSize: 11,
              color: "#64748b",
              cursor: "pointer",
            }}
            title="Restore the sections and order generated by AI"
          >
            Reset
          </button>
        </div>
      )}

      <div style={containerStyle}>
        {nodes.map((node, index) => (
          <SortableItem
            key={`${node.tag}-${index}`}
            index={index}
            editable={editable}
            isDragTarget={dragOver === index}
            onDragStart={handleDragStart}
            onDragOver={handleDragOver}
            onDrop={handleDrop}
            onDragEnd={() => {
              dragFrom.current = null;
              setDragOver(null);
            }}
            onRemove={handleRemove}
          >
            {renderNode(node, (nextNode) => {
              updateNodes(
                nodes.map((currentNode, currentIndex) =>
                  currentIndex === index ? nextNode : currentNode
                )
              );
            })}
          </SortableItem>
        ))}
      </div>
    </div>
  );
}
